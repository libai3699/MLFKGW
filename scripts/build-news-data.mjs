import fs from 'fs';
import path from 'path';

const root = path.resolve('d:/ML/gw');
const htmlPath = path.join(root, 'pages-src/news.html');
const outputPath = path.join(root, 'src/data/newsData.js');

const html = fs.readFileSync(htmlPath, 'utf8');

function decodeHtml(text) {
  return text
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/\s+/g, ' ')
    .trim();
}

const years = [];
const itemRegex =
  /<div class="accordion-item">[\s\S]*?<button class="accordion-button([^"]*)"[\s\S]*?>\s*(\d{4})\s*[\s\S]*?<ul>([\s\S]*?)<\/ul>/g;

let match;
while ((match = itemRegex.exec(html)) !== null) {
  const isOpen = !match[1].includes('collapsed');
  const year = match[2];
  const listHtml = match[3];
  const items = [];

  const rowRegex =
    /<li class="row">[\s\S]*?<span class="col-xs-12 col-lg-3 text-lg-end">\s*([\s\S]*?)\s*<\/span>[\s\S]*?<a target="_blank" href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/g;

  let rowMatch;
  while ((rowMatch = rowRegex.exec(listHtml)) !== null) {
    items.push({
      date: decodeHtml(rowMatch[1]),
      href: rowMatch[2].startsWith('http')
        ? rowMatch[2]
        : `https://www.artisanpartners.com${rowMatch[2]}`,
      title: decodeHtml(rowMatch[3]),
    });
  }

  years.push({ year, defaultOpen: isOpen, items });
}

const sidebar = {
  pressInquiries: {
    heading: 'FOR PRESS INQUIRIES',
    name: 'Eileen Kwei',
    phone: '1 800 399 1770 (United States)',
  },
  artisanCanvas: {
    heading: 'ARTISAN CANVAS',
    description:
      'Timely insights and updates from our investment teams and firm leadership',
    cta: 'View Our Blog',
    href: 'https://www.artisancanvas.com',
  },
};

const fileContents = `/* Auto-generated by scripts/build-news-data.mjs */
export const newsPage = {
  title: 'News',
  years: ${JSON.stringify(years, null, 2)},
  sidebar: ${JSON.stringify(sidebar, null, 2)},
};
`;

fs.writeFileSync(outputPath, fileContents);
console.log(`Wrote ${outputPath} (${years.length} years, ${years.reduce((n, y) => n + y.items.length, 0)} items)`);
