function transformHtml(html) {
  return html
    .replace(/\/content\/dam\/images\/sustainability-esg\/2025\//g, '/images/sustainability/')
    .replace(/\/content\/dam\/images\/logo\//g, '/images/sustainability/')
    .replace(/href="\/sustainability\/([^"#]+)\.html(#[^"]*)?"/g, 'href="/sustainability/$1$2"')
    .replace(/href="\/sustainability\/home\.html"/g, 'href="/sustainability/home"')
    .replace(/\sclass="row>"/g, ' class="row"')
    .replace(/<script[\s\S]*?<\/script>/gi, '')
    .trim();
}

function extractMain(html) {
  const match = html.match(/<main>([\s\S]*?)<\/main>/i);
  if (!match) {
    throw new Error('Missing <main> content');
  }
  return transformHtml(match[1]);
}

const pages = pageConfigs.map((config) => {
  const htmlPath = path.join(pagesDir, config.file);
  const source = fs.readFileSync(htmlPath, 'utf8');
  const contentHtml = extractMain(source);

  return {
    slug: config.slug,
    title: config.title,
    activeNavId: config.activeNavId,
    contentHtml,
  };
});

const fileContents = `/* Auto-generated by scripts/build-sustainability-content.mjs */
export const sustainabilityPages = ${JSON.stringify(
  Object.fromEntries(pages.map((page) => [page.slug, page])),
  null,
  2,
)};

export const sustainabilityPageSlugs = ${JSON.stringify(pages.map((page) => page.slug))};
`;

fs.writeFileSync(outputFile, fileContents);
